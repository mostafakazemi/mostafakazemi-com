import fs from "node:fs/promises";
import path from "node:path";
import { fileURLToPath } from "node:url";

const __dirname = path.dirname(fileURLToPath(import.meta.url));
const rootDir = path.resolve(__dirname, "..");
const caseStudyDir = path.join(rootDir, "src/data/case-studies");
const generatedPath = path.join(caseStudyDir, "generated.ts");
const ignoredFiles = new Set(["generated.ts", "index.ts", "types.ts"]);

function toIdentifier(fileName) {
  return fileName
    .replace(/\.ts$/, "")
    .split(/[^a-zA-Z0-9]+/)
    .filter(Boolean)
    .map((part, index) => {
      const normalized = part.replace(/^[0-9]+/, "");
      if (!normalized) {
        return "";
      }
      return index === 0
        ? normalized.charAt(0).toLowerCase() + normalized.slice(1)
        : normalized.charAt(0).toUpperCase() + normalized.slice(1);
    })
    .join("");
}

const files = (await fs.readdir(caseStudyDir))
  .filter((file) => file.endsWith(".ts") && !ignoredFiles.has(file))
  .sort();

const imports = files.map((file) => {
  const identifier = toIdentifier(file);
  const modulePath = `./${file.replace(/\.ts$/, "")}`;
  return `import { caseStudy as ${identifier} } from "${modulePath}";`;
});

const identifiers = files.map(toIdentifier).filter(Boolean);

const output = [
  "// This file is generated by scripts/generate-case-study-registry.mjs.",
  "// The build regenerates it from sibling case-study files.",
  'import type { CaseStudy } from "./types";',
  ...imports,
  "",
  `export const caseStudies = [${identifiers.join(", ")}] satisfies CaseStudy[];`,
  ""
].join("\n");

await fs.writeFile(generatedPath, output);
console.log(`Generated ${path.relative(rootDir, generatedPath)} with ${files.length} case study file(s)`);
